/* wordfreq.h — спільні оголошення ЛР 4. Не змінюйте цей файл.
 *
 * Програма складається з трьох частин:
 *   scan.c        — розбиває байти на слова (готово);
 *   table_*.c     — зберігає слова й лічильники (naive — готово, hash — ваше);
 *   main.c        — аргументи, файли, помилки, вивід (ваше).
 */
#ifndef WORDFREQ_H
#define WORDFREQ_H

#include <stddef.h>

/* ---- Таблиця «слово → кількість» ------------------------------------ */

struct table;                    /* неповний тип: вміст знає лише table_*.c */

struct entry {
    char         *word;          /* рядок із завершальним '\0', належить таблиці */
    unsigned long count;
};

/* Повертає NULL, якщо не вистачило пам'яті. */
struct table *table_new(void);

/* Додає одне входження слова довжиною len (без '\0' в кінці).
 * Таблиця копіює слово. Повертає 0 або -1, якщо не вистачило пам'яті. */
int table_add(struct table *t, const char *word, size_t len);

/* Кількість різних слів. */
size_t table_size(const struct table *t);

/* Повертає масив із table_size(t) вказівників на записи таблиці
 * (порядок довільний) або NULL, якщо не вистачило пам'яті.
 * Масив звільняє той, хто викликав, — free(); самі записи — ні. */
struct entry **table_entries(const struct table *t);

/* Звільняє таблицю разом з усіма словами. table_free(NULL) нічого не робить. */
void table_free(struct table *t);

/* ---- Розбиття на слова ------------------------------------------------ */

/* Слово — максимальна послідовність байтів, кожен з яких є латинською
 * літерою або має старший біт 1 (так до слова потрапляють байти UTF-8,
 * зокрема кирилиця). Латинські літери переводяться в нижній регістр,
 * решта байтів — без змін. Слово може бути розрізане між двома
 * викликами scanner_feed: сканер це враховує. */
struct scanner {
    char  *buf;                  /* незавершене слово з попереднього шматка */
    size_t len, cap;
};

void scanner_init(struct scanner *s);
/* 0 або -1, якщо не вистачило пам'яті. */
int  scanner_feed(struct scanner *s, const char *data, size_t n, struct table *t);
/* Кінець даних одного файла: дописати останнє слово. 0 або -1. */
int  scanner_finish(struct scanner *s, struct table *t);
void scanner_free(struct scanner *s);

/* ---- Звіт ------------------------------------------------------------- */

/* Друкує в stdout не більше n рядків «КІЛЬКІСТЬ СЛОВО», упорядкованих
 * за спаданням кількості, а за однакової кількості — за зростанням слова
 * (побайтово, як strcmp). Повертає 0 або -1, якщо не вистачило пам'яті.
 * Помилок запису функція НЕ перевіряє — це робить main(). */
int report_top(const struct table *t, size_t n);

#endif
